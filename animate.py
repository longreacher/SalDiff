# Load and format the data
df = pd.read_csv(io.StringIO(data), sep='\t')
df['Date'] = pd.to_datetime(df['Date'])

# Determine required frames and frame rate for a 15-second video
num_frames = len(df)
target_duration = 15.0
fps = num_frames / target_duration

fig, ax = plt.subplots(figsize=(10, 6))

def update(frame):
    ax.clear()
    
    # Get the data up to the current frame
    current_data = df.iloc[:frame+1]
    
    dates = current_data['Date']
    diffs = current_data['Cumulative Difference in Salary']
    
    # Plot the main line
    ax.plot(dates, diffs, color='black', linewidth=1.5)
    
    # Tint positive values green and negative values red
    ax.fill_between(dates, diffs, 0, where=(diffs >= 0), interpolate=True, color='green', alpha=0.5)
    ax.fill_between(dates, diffs, 0, where=(diffs < 0), interpolate=True, color='red', alpha=0.5)
    
    # Draw a line at zero for reference
    ax.axhline(0, color='grey', linewidth=1, linestyle='--')
    
    # Auto-scale axis to only show revealed data points
    if len(current_data) > 1:
        ax.set_xlim(dates.min(), dates.max())
        
        y_min, y_max = diffs.min(), diffs.max()
        padding = max(abs(y_max), abs(y_min)) * 0.1 if y_max != y_min else 100
        ax.set_ylim(y_min - padding, y_max + padding)
    
    # Formatting the plot
    ax.set_title("Cumulative Salary Difference: VP vs. Subject Coordinator")
    ax.set_xlabel("Date")
    ax.set_ylabel("Cumulative Difference ($)")
    plt.xticks(rotation=45)
    plt.tight_layout()

# Create the animation
ani = animation.FuncAnimation(fig, update, frames=num_frames, repeat=False)

# Save as a 15-second MP4 video
output_filename = "salary_difference.mp4"
print(f"Saving {output_filename} at {fps:.2f} FPS...")
ani.save(output_filename, writer='ffmpeg', fps=fps)
print("Done!")
